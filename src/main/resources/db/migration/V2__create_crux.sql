CREATE TABLE crux (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      trail_id BIGINT NOT NULL REFERENCES trail (id),
                      name VARCHAR(200) NOT NULL,
                      position INTEGER NOT NULL,
                      description VARCHAR(1000) NOT NULL
);

