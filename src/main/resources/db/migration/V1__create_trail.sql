CREATE TABLE trail (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       name VARCHAR(200) NOT NULL,
                       start_point VARCHAR(200) NOT NULL,
                       distance DOUBLE PRECISION NOT NULL,
                       technical_difficulty DOUBLE PRECISION NOT NULL,
                       exposure DOUBLE PRECISION NOT NULL,
                       condition DOUBLE PRECISION NOT NULL,
                       CONSTRAINT trail_technical_chk CHECK (technical_difficulty BETWEEN 1 AND 5),
                       CONSTRAINT trail_exposure_chk CHECK (exposure BETWEEN 1 AND 5),
                       CONSTRAINT trail_condition_chk CHECK (condition BETWEEN 1 AND 5)
);

